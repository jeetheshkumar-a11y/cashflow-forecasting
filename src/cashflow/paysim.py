"""PaySim loader (https://www.kaggle.com/datasets/ealaxi/paysim1).

PaySim is a synthetic mobile-money dataset generated by an agent-based
simulator that was *calibrated on one month of real transaction logs* from
an African mobile-money service.  It is therefore a useful second dataset
that our own simulator did not produce.

Important limitations (stated honestly in the README):
  * it covers only 743 hourly steps (~31 days);
  * almost every customer (``nameOrig``) appears only once or twice, so
    per-person 30-day forecasting is impossible with PaySim.

So we use it at the *aggregate* level: hourly total inflow (CASH_IN) and
outflow (CASH_OUT, PAYMENT, TRANSFER, DEBIT) for the whole platform, and
forecast the next 24 hours from the previous 7 days.  This is the same
"income vs. expenses" problem at a different scale and frequency.

Download ``PS_20174392719_1491204439457_log.csv`` from Kaggle and place it in
``data/`` (it is ~470 MB, so it is git-ignored).
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

INFLOW_TYPES = ("CASH_IN",)
OUTFLOW_TYPES = ("CASH_OUT", "PAYMENT", "TRANSFER", "DEBIT")
DEFAULT_PATH = Path(__file__).resolve().parents[2] / "data" / "PS_20174392719_1491204439457_log.csv"


def load_paysim_hourly(path: str | Path = DEFAULT_PATH, chunksize: int = 1_000_000) -> pd.DataFrame:
    """Aggregate PaySim into an hourly frame with columns
    ``step, income, expense`` (income = inflow, expense = outflow).

    Reads in chunks so it works on a laptop with little RAM."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f"PaySim CSV not found at {path}. Download it from "
            "https://www.kaggle.com/datasets/ealaxi/paysim1 and put it in data/."
        )
    parts = []
    for chunk in pd.read_csv(path, usecols=["step", "type", "amount"], chunksize=chunksize):
        chunk["flow"] = "other"
        chunk.loc[chunk["type"].isin(INFLOW_TYPES), "flow"] = "income"
        chunk.loc[chunk["type"].isin(OUTFLOW_TYPES), "flow"] = "expense"
        parts.append(chunk.groupby(["step", "flow"])["amount"].sum())
    agg = pd.concat(parts).groupby(level=[0, 1]).sum().unstack(fill_value=0.0)
    steps = pd.RangeIndex(int(agg.index.min()), int(agg.index.max()) + 1, name="step")
    agg = agg.reindex(steps, fill_value=0.0)
    out = pd.DataFrame({
        "step": steps,
        "income": agg.get("income", 0.0).values,
        "expense": agg.get("expense", 0.0).values,
    })
    # a fake hourly timestamp makes plotting / calendar features easy
    out["date"] = pd.Timestamp("2017-01-01") + pd.to_timedelta(out["step"] - 1, unit="h")
    return out
